#!/usr/bin/env node
// Fetches the Google Calendar iCal feed at BOOKINGS_ICAL_URL and rewrites
// src/data/booked.ts with the list of booked dates (YYYY-MM-DD).
//
// Behavior:
// - URL not set: warn and exit 0 without modifying the file. Lets local dev
//   and unconfigured CI builds proceed using whatever's checked in.
// - URL set but fetch/parse fails: exit 1 so the workflow fails loudly and
//   the deploy doesn't ship stale or empty data unintentionally.
//
// Only event *dates* are written out — no titles, attendees, or notes ever
// leave this script, so the repo can stay public.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ical from "node-ical";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const OUT_PATH = path.resolve(__dirname, "..", "src", "data", "booked.ts");

const ICAL_URL = process.env.BOOKINGS_ICAL_URL;

if (!ICAL_URL) {
  console.warn(
    "[sync-bookings] BOOKINGS_ICAL_URL not set — skipping calendar sync. " +
      "Existing src/data/booked.ts will be used as-is."
  );
  process.exit(0);
}

const toIsoDate = (d) => {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
};

const expandRange = (start, end) => {
  const dates = [];
  const cur = new Date(start);
  cur.setHours(0, 0, 0, 0);
  const stop = new Date(end);
  stop.setHours(0, 0, 0, 0);
  // iCal DTEND is exclusive for all-day events; include start, exclude end.
  while (cur < stop) {
    dates.push(toIsoDate(cur));
    cur.setDate(cur.getDate() + 1);
  }
  // Single-day event (start == end or no end): include start.
  if (dates.length === 0) dates.push(toIsoDate(start));
  return dates;
};

const formatFile = (dates) => `// AUTOGENERATED by scripts/sync-bookings.mjs at build time, sourced from
// the Google Calendar iCal feed at BOOKINGS_ICAL_URL.
//
// Edits below survive locally for testing, but are overwritten by the next
// CI build. Permanent bookings should live in the calendar.
export const bookedDates: readonly string[] = [
${dates.map((d) => `  "${d}",`).join("\n")}
];
`;

async function main() {
  console.log("[sync-bookings] fetching iCal feed…");
  // node-ical's types miss the Promise return on async.fromURL; the runtime
  // value is a thenable, so wrapping in Promise.resolve is a safe no-op.
  const events = await Promise.resolve(ical.async.fromURL(ICAL_URL));
  const dates = new Set();
  const horizonStart = new Date();
  horizonStart.setHours(0, 0, 0, 0);

  for (const ev of Object.values(events)) {
    if (!ev || ev.type !== "VEVENT" || !ev.start) continue;
    const start = new Date(ev.start);
    const end = ev.end ? new Date(ev.end) : start;
    for (const d of expandRange(start, end)) {
      // Skip past dates — the date-checker rejects them client-side too,
      // and keeping the file tight avoids noise.
      if (new Date(`${d}T00:00:00`) >= horizonStart) dates.add(d);
    }
  }

  const sorted = [...dates].sort();
  writeFileSync(OUT_PATH, formatFile(sorted));
  console.log(
    `[sync-bookings] wrote ${sorted.length} date(s) to src/data/booked.ts`
  );
}

main().catch((err) => {
  console.error("[sync-bookings] failed:", err?.message ?? err);
  process.exit(1);
});
